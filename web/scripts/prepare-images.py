"""Generate responsive WebP copies without modifying source photographs.

Run manually after adding photographs: python3 scripts/prepare-images.py
Requires Pillow; generated files are checked in for ordinary npm builds.
"""
from pathlib import Path
import json
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
assets = root / "public/assets"
manifest = {}
for folder in ("garden", "jiangnan/photos", "jiangnan/works"):
    for source in sorted((assets / folder).glob("*.jpg")):
        with Image.open(source) as original:
            image = ImageOps.exif_transpose(original).convert("RGB")
            widths = sorted({min(image.width, width) for width in (480, 960, 1600)})
            variants = []
            for width in widths:
                target = assets / "optimized" / folder / f"{source.stem}-{width}.webp"
                target.parent.mkdir(parents=True, exist_ok=True)
                resized = image.resize((width, round(image.height * width / image.width)), Image.Resampling.LANCZOS)
                resized.save(target, "WEBP", quality=82, method=6)
                variants.append({"src": "/" + str(target.relative_to(root / "public")), "width": width})
            manifest["/" + str(source.relative_to(root / "public"))] = variants
(root / "src/data/image-variants.js").write_text(
    "// Generated by scripts/prepare-images.py; originals remain in public/assets.\n"
    + "export const imageVariants = " + json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
    encoding="utf-8",
)
print(f"Generated responsive copies for {len(manifest)} photographs")
